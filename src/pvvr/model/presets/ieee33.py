_LINE_AMPERES = 400.0  # 统一载流量占位（原文献未给，仅供负载率参考）


def build_dict() -> dict:
    """生成 IEEE 33 三相项目 dict。"""
    nodes = []
    for i in range(1, 34):
        p, q = _LOADS.get(i, (0.0, 0.0))
        nodes.append({
            "id": str(i),
            "phases": ["A", "B", "C"],
            "name": "节点 %d" % i,
            "x": None,
            "y": None,
            "load_kw": {"A": p / 3.0, "B": p / 3.0, "C": p / 3.0},
            "load_kvar": {"A": q / 3.0, "B": q / 3.0, "C": q / 3.0},
        })
    lines = []
    for k, (f, t, r, x) in enumerate(_BRANCHES, start=1):
        lines.append({
            "id": "L%02d" % k,
            "from": str(f),
            "to": str(t),
            "phases": ["A", "B", "C"],
            "length_km": 1.0,          # 表值为整条线路总阻抗，按 1 km 折算 Ω/km
            "r_ohm_per_km": {"A": r, "B": r, "C": r},
            "x_ohm_per_km": {"A": x, "B": x, "C": x},
            "ampacity_a": _LINE_AMPERES,
            "line_type": "",
        })
    return {
        "schema_version": 1,
        "name": "IEEE 33 节点（三相基态）",
        "base": {
            "v_base_kv": 12.66,
            "frequency_hz": 50.0,
            "s_base_kva": 1000.0,
            "slack": {"node": "1", "v_pu": 1.0},
            "v_min_pu": 0.95,
            "v_max_pu": 1.05,
        },
        "nodes": nodes,
        "lines": lines,
        "line_types": [],
        "pvs": [],
        "curves": {"load": LOAD_CURVE, "pv": PV_CURVE},
        "comm_graph": {"edges": []},
        "algo": {},
    }
