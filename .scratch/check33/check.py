def sweep(table):
    """前推回代（单相平衡等值），返回 (最低电压pu, 最低电压母线, 损耗kW, 迭代数)。"""
    kv_ll = 12.66                          # 线电压基准 kV
    sbase_kva = 1000.0                     # 1 MVA（三相总）
    zb = kv_ll ** 2 * 1000.0 / sbase_kva   # 阻抗基准 ohm = kV_LL²/MVA = 160.28
    n = 33
    adj = {i: [] for i in range(1, n + 1)}
    for f, t, r, x in table:
        adj[f].append((t, complex(r, x) / zb))
    parent = {1: (None, 0j)}
    order = []
    stack = [1]
    seen = {1}
    while stack:
        u = stack.pop()
        order.append(u)
        for v, z in adj[u]:
            if v not in seen:
                seen.add(v)
                parent[v] = (u, z)
                stack.append(v)
    assert len(seen) == n, "网络不连通或有环"
    s = {b: 0j for b in range(1, n + 1)}
    for b, (p, q) in LOADS.items():
        s[b] = complex(p, q) / sbase_kva
    v = {b: 1 + 0j for b in range(1, n + 1)}
    ibr = {b: 0j for b in range(1, n + 1)}
    it = 0
    for it in range(1, 10000):
        for b in range(1, n + 1):
            ibr[b] = (s[b] / v[b]).conjugate()
        for u in reversed(order):
            if u == 1:
                continue
            p, _ = parent[u]
            if p is not None:
                ibr[p] = ibr[p] + ibr[u]
        vold = dict(v)
        for u in order[1:]:
            p, z = parent[u]
            v[u] = v[p] - z * ibr[u]
        err = max(abs(v[b] - vold[b]) for b in range(1, n + 1))
        if err < 1e-9:
            break
    vmin = min((abs(v[b]), b) for b in range(1, n + 1))
    loss_kw = sum(abs(ibr[t]) ** 2 * (parent[t][1]).real * sbase_kva
                  for t in range(2, n + 1))
    return vmin[0], vmin[1], loss_kw, it


